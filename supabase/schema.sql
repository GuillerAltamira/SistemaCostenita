-- ==============================================================================
-- 5. INALTERABILIDAD DE REGISTROS COMERCIALES CERRADOS (ASFI / Cód. Comercio)
-- ==============================================================================

CREATE OR REPLACE FUNCTION fn_bloquear_modificacion_registros_cerrados()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Operación denegada: Las transacciones de compra, venta o inventario no se pueden eliminar físicamente. Registre una anulación para preservar la inalterabilidad contable (Código de Comercio Art. 40, ASFI).';
    ELSIF TG_OP = 'UPDATE' AND OLD.estado IN ('REGISTRADA', 'COMPLETADA', 'ANULADA') AND NEW.estado = OLD.estado THEN
        IF OLD.total <> NEW.total OR OLD.cantidad <> NEW.cantidad OR OLD.id_producto <> NEW.id_producto THEN
            RAISE EXCEPTION 'Operación denegada: No está permitido alterar retroactivamente precios ni cantidades de transacciones comerciales ya cerradas (Normativa ASFI / Ley N° 164).';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_bloquear_modificacion_compra ON compra;
CREATE TRIGGER trg_bloquear_modificacion_compra
BEFORE UPDATE OR DELETE ON compra
FOR EACH ROW
EXECUTE FUNCTION fn_bloquear_modificacion_registros_cerrados();

DROP TRIGGER IF EXISTS trg_bloquear_modificacion_venta ON venta;
