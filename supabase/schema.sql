CREATE OR REPLACE FUNCTION fn_crear_inventario_producto()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO inventario (id_producto, stock_actual, unidad_medida)
    VALUES (NEW.id_producto, 0, 'UNIDAD')
    ON CONFLICT (id_producto) DO NOTHING;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_crear_inventario_producto ON producto;
CREATE TRIGGER trg_crear_inventario_producto
AFTER INSERT ON producto
FOR EACH ROW
EXECUTE FUNCTION fn_crear_inventario_producto();

CREATE OR REPLACE FUNCTION fn_actualizar_stock_movimiento()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.tipo = 'ENTRADA' THEN
        UPDATE inventario
        SET stock_actual = stock_actual + NEW.cantidad,
            updated_at = NOW()
        WHERE id_producto = NEW.id_producto;
    ELSIF NEW.tipo = 'SALIDA' THEN
        IF (SELECT stock_actual FROM inventario WHERE id_producto = NEW.id_producto) < NEW.cantidad THEN
            RAISE EXCEPTION 'Stock insuficiente para realizar la salida del producto ID %', NEW.id_producto;
        END IF;

        UPDATE inventario
        SET stock_actual = stock_actual - NEW.cantidad,
            updated_at = NOW()
        WHERE id_producto = NEW.id_producto;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_actualizar_stock_movimiento ON movimiento_inventario;
CREATE TRIGGER trg_actualizar_stock_movimiento
AFTER INSERT ON movimiento_inventario
FOR EACH ROW
EXECUTE FUNCTION fn_actualizar_stock_movimiento();

