-- 0. EXTENSIONES DE SEGURIDAD Y CRIPTOGRAFÍA
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ==============================================================================
-- 1. TABLA DE AUDITORÍA INALTERABLE (Normativa ASFI / Ley 164 Art. 79)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS logs_auditoria (
    id_log BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tabla_afectada VARCHAR(50) NOT NULL,
    operacion VARCHAR(10) NOT NULL CHECK (operacion IN ('INSERT', 'UPDATE', 'DELETE', 'SELECT')),
    usuario_id UUID DEFAULT auth.uid(),
    datos_anteriores JSONB,
    datos_nuevos JSONB,
    hash_anterior TEXT,
    hash_integridad TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Trigger de Inalterabilidad Estricta: Prohibir cualquier UPDATE o DELETE en logs_auditoria
CREATE OR REPLACE FUNCTION fn_bloquear_alteracion_auditoria()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'Operación denegada: Los registros de la tabla logs_auditoria son inalterables e indelebles según la normativa ASFI y la Ley N° 164 Art. 79.';
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_bloquear_alteracion_auditoria ON logs_auditoria;
CREATE TRIGGER trg_bloquear_alteracion_auditoria
BEFORE UPDATE OR DELETE ON logs_auditoria
FOR EACH ROW
EXECUTE FUNCTION fn_bloquear_alteracion_auditoria();

-- ==============================================================================
-- 2. TABLAS DE DOMINIO DE NEGOCIO (Normalizadas en 3FN)
-- ==============================================================================

-- TABLA: PRODUCTO (Catálogo de Miel y Derivados)
CREATE TABLE IF NOT EXISTS producto (
    id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    presentacion VARCHAR(50) NOT NULL,
    precio_venta NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (precio_venta >= 0),
    descripcion TEXT,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO', 'INACTIVO')),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT uq_producto_nombre_presentacion UNIQUE (nombre, presentacion)
);

-- TABLA: PROVEEDOR (Apicultores locales con PII Protegido)
CREATE TABLE IF NOT EXISTS proveedor (
    id_proveedor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    telefono VARCHAR(200) NOT NULL UNIQUE, -- Almacena dato sensible cifrado o enmascarado
    localidad VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- TABLA: INVENTARIO (Relación 1:1 con Producto)
CREATE TABLE IF NOT EXISTS inventario (
    id_inventario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto BIGINT NOT NULL UNIQUE REFERENCES producto(id_producto) ON DELETE CASCADE,
    stock_actual NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (stock_actual >= 0),
    unidad_medida VARCHAR(20) NOT NULL DEFAULT 'UNIDAD' CHECK (unidad_medida IN ('GRAMOS', 'KG', 'UNIDAD')),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- TABLA: COMPRA (Acopio de miel a proveedores - Gestión por Peso)
CREATE TABLE IF NOT EXISTS compra (
    id_compra BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL DEFAULT CURRENT_DATE,
    cantidad NUMERIC(10, 2) NOT NULL CHECK (cantidad > 0),
    unidad_medida VARCHAR(20) NOT NULL CHECK (unidad_medida IN ('GRAMOS', 'KG', 'UNIDAD')),
    estado VARCHAR(20) NOT NULL DEFAULT 'REGISTRADA' CHECK (estado IN ('REGISTRADA', 'ANULADA')),
    id_proveedor BIGINT NOT NULL REFERENCES proveedor(id_proveedor),
    id_producto BIGINT NOT NULL REFERENCES producto(id_producto),
    precio_unitario NUMERIC(10, 2) DEFAULT 0,
    total NUMERIC(10, 2) DEFAULT 0,
    observaciones TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- TABLA: MOVIMIENTO_INVENTARIO (Kardex / Inalterabilidad de movimientos)
CREATE TABLE IF NOT EXISTS movimiento_inventario (
    id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto BIGINT NOT NULL REFERENCES producto(id_producto),
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('ENTRADA', 'SALIDA', 'AJUSTE')),
    cantidad NUMERIC(10, 2) NOT NULL CHECK (cantidad > 0),
    unidad_medida VARCHAR(20) NOT NULL DEFAULT 'UNIDAD' CHECK (unidad_medida IN ('GRAMOS', 'KG', 'UNIDAD')),
    fecha DATE NOT NULL DEFAULT CURRENT_DATE,
    motivo VARCHAR(200),
    id_referencia BIGINT, -- id_compra o id_venta según corresponda
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- TABLA: VENTA (Comercialización de miel a clientes)
CREATE TABLE IF NOT EXISTS venta (
    id_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL DEFAULT CURRENT_DATE,
    cliente VARCHAR(100) NOT NULL DEFAULT 'Cliente Mostrador',
    id_producto BIGINT NOT NULL REFERENCES producto(id_producto),
    cantidad NUMERIC(10, 2) NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(10, 2) NOT NULL,
    total NUMERIC(10, 2) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'COMPLETADA' CHECK (estado IN ('COMPLETADA', 'ANULADA')),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

