-- 3. FUNCIONES DE CRIPTOGRAFÍA Y SEGURIDAD (pgcrypto)
-- ==============================================================================

-- Función helper para cifrar texto sensible (Teléfono / PII)
CREATE OR REPLACE FUNCTION fn_cifrar_texto(p_texto TEXT)
RETURNS TEXT AS $$
BEGIN
    IF p_texto IS NULL OR p_texto = '' THEN
        RETURN p_texto;
    END IF;
    RETURN encode(pgp_sym_encrypt(p_texto, 'CLAVE_SECRETA_COSTENITA_ASFI_2026'), 'base64');
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Función helper para descifrar texto sensible (Teléfono / PII)
CREATE OR REPLACE FUNCTION fn_descifrar_texto(p_cifrado TEXT)
RETURNS TEXT AS $$
BEGIN
    IF p_cifrado IS NULL OR p_cifrado = '' THEN
        RETURN p_cifrado;
    END IF;
    BEGIN
        RETURN pgp_sym_decrypt(decode(p_cifrado, 'base64'), 'CLAVE_SECRETA_COSTENITA_ASFI_2026');
    EXCEPTION WHEN OTHERS THEN
        -- Si el texto no está encriptado previamente, retorna el valor plano para mantener retrocompatibilidad
        RETURN p_cifrado;
    END;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- ==============================================================================
-- 4. SISTEMA DE AUDITORÍA AUTOMÁTICA CON HASH ENCADENADO (SHA-256)
-- ==============================================================================

CREATE OR REPLACE FUNCTION fn_auditar_transaccion()
RETURNS TRIGGER AS $$
DECLARE
    v_hash_ant TEXT;
    v_hash_nuevo TEXT;
    v_datos_ant JSONB := NULL;
    v_datos_nuev JSONB := NULL;
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        v_datos_ant := to_jsonb(OLD);
    END IF;
    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        v_datos_nuev := to_jsonb(NEW);
    END IF;

    -- Obtener el último hash para el encadenamiento criptográfico (Bloque de auditoría ASFI)
    SELECT hash_integridad INTO v_hash_ant
    FROM logs_auditoria
    ORDER BY id_log DESC
    LIMIT 1;

    IF v_hash_ant IS NULL THEN
        v_hash_ant := 'GENESIS_COSTENITA_ASFI_2026';
    END IF;

    -- Generar SHA-256 encadenado combinando tabla, operación, usuario, datos y marca temporal
    v_hash_nuevo := encode(
        digest(
            v_hash_ant ||
            TG_TABLE_NAME ||
            TG_OP ||
            COALESCE(auth.uid()::text, 'ANONYMOUS_USER') ||
            COALESCE(v_datos_ant::text, '{}') ||
            COALESCE(v_datos_nuev::text, '{}') ||
            NOW()::text,
            'sha256'
        ),
        'hex'
    );

    INSERT INTO logs_auditoria (
        tabla_afectada,
        operacion,
        usuario_id,
        datos_anteriores,
        datos_nuevos,
        hash_anterior,
        hash_integridad
    ) VALUES (
        TG_TABLE_NAME,
        TG_OP,
        auth.uid(),
        v_datos_ant,
        v_datos_nuev,
        v_hash_ant,
        v_hash_nuevo
    );

    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

